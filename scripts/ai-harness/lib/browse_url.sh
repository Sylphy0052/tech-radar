#!/usr/bin/env bash
# 起動後にブラウザで開く URL のホストを決める（Issue #85）。
#
# `run.sh` は案内文へ `BIND_HOST` をそのまま流用していた。`BIND_HOST` は listen する
# インターフェースの指定であって、ブラウザで開く URL のホストとは別物である。既定の
# `127.0.0.1` で案内され、そのとおりに開くと API 呼び出しがすべて CORS で弾かれていた
# （許可オリジンは `http://localhost:13700` で、`localhost` と `127.0.0.1` は CORS 上は
# 別オリジンとして扱われる。`CORSMiddleware` は完全一致で比較する）。
#
# 症状が分かりにくい。バックエンドは 200 を返し DB にも書き込まれるが、ブラウザが
# レスポンスを読めないため UI だけが「通信に失敗しました」と出る。
#
# 呼び出し元の `log` / `fail` を使う。単体で実行するものではない。

# ブラウザで開く URL のホストを返す。
#
# ループバック（`127.0.0.1` / `localhost` / `::1`）と全インターフェース
# （`0.0.0.0` / `::`）は `localhost` へ倒す。前者は CORS の許可オリジンに合わせるため、
# 後者はそもそも開く先にならないため（「どのインターフェースでも受ける」という意味の
# 特殊なアドレスであって、宛先ではない）。
#
# それ以外の値はそのまま返す。別端末から開く運用では、その端末から届くホストで案内
# しないと意味がない（`.env.example` のとおり、その場合は `CORS_ALLOW_ORIGINS` と
# `NEXT_PUBLIC_API_BASE_URL` を利用者が揃える）。
#
# 案内のための関数が起動を止めるのは本末転倒なので、引数が無くても落とさない。
browse_host() {
  local bind_host="${1:-}"
  case "$bind_host" in
    "" | 0.0.0.0 | 127.0.0.1 | localhost | :: | ::1)
      printf 'localhost'
      ;;
    *)
      # `echo` はエスケープの解釈が処理系で変わる。値をそのまま返す。
      printf '%s' "$bind_host"
      ;;
  esac
}
